// Sorted keys from longest to shortest for accurate substring replacement without collisions
export const SORTED_KEYS = Object.keys(DICTIONARY).sort((a, b) => b.length - a.length)

export function translatePhrase(text: string): string {
  if (!text) return text
  const trimmed = text.trim()
  if (DICTIONARY[trimmed]) {
    return text.replace(trimmed, DICTIONARY[trimmed])
  }
  let res = text
  for (const hi of SORTED_KEYS) {
    if (res.includes(hi)) {
      res = res.split(hi).join(DICTIONARY[hi])
    }
  }
  return res
}
